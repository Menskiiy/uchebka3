<h2 style="font-size:17px;margin:22px 0 8px">Что такое градусы</h2>
Каждой публикации сообщество ставит оценку: «горячо» или «холодно».
Из этих голосов складывается градус — чем он выше, тем выгоднее предложение
по мнению участников.

Голос новичка весит меньше голоса человека с высокой репутацией. Так пачка
свежих аккаунтов не сможет вытолкнуть наверх слабое предложение.

За собственную публикацию голосовать нельзя.

<h2 style="font-size:17px;margin:22px 0 8px">Что значит «Проверено»</h2>
Зелёная отметка означает, что модератор открыл предложение и убедился:
ссылка работает, промокод действует, условия описаны верно.

Отсутствие отметки не значит, что предложение плохое — просто до него ещё
не дошли руки.

<h2 style="font-size:17px;margin:22px 0 8px">Срок действия</h2>
У скидок и промокодов указан срок. Когда он выходит, предложение уходит
из ленты и помечается как истёкшее — но остаётся доступным по прямой ссылке
вместе с комментариями.

<h2 style="font-size:17px;margin:22px 0 8px">Репутация и ранги</h2>
Репутация растёт, когда другим нравятся ваши публикации и комментарии.
С ней растёт и вес вашего голоса, и ранг рядом с именем: Наблюдатель,
Новичок, Охотник, Знаток, Легенда.

<h2 style="font-size:17px;margin:22px 0 8px">Первые публикации</h2>
Первые две публикации нового участника проходят проверку модератором —
это защита от спама. Дальше ваши посты появляются в ленте сразу.

<h2 style="font-size:17px;margin:22px 0 8px">Что можно публиковать</h2>
Скидки и промокоды — конкретные предложения магазинов.
Обсуждения — вопросы к сообществу.
Блог — гайды, разборы кэшбэка, личный опыт.

Заведомо неверные цены, реклама без скидки и оскорбления удаляются,
а при повторе аккаунт блокируется. Подробнее — в
<a href="<?= e(legal_url('terms')) ?>">пользовательском соглашении</a>.

<h2 style="font-size:17px;margin:22px 0 8px">Нашли ошибку или спам</h2>
Под каждой публикацией и комментарием есть ссылка «Пожаловаться».
Жалобы попадают модераторам, разбор занимает обычно несколько часов.

